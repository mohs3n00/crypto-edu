export function getCoverageStats() {
  const totalItems = artboardCoverageMatrix.length;
  const completed = artboardCoverageMatrix.filter((c) => c.status === 'completed').length;
  const gaps = artboardCoverageMatrix.filter((c) => c.status === 'gap-theoretical-only').length;
  const officialExams = artboardCoverageMatrix.filter((c) => c.sourceType === 'official-exam').length;
  const lectureSlides = artboardCoverageMatrix.filter((c) => c.sourceType === 'lecture-slide').length;
  const variationsTotal = artboardCoverageMatrix.reduce((sum, item) => sum + item.variationsCount, 0);

  return {
    totalItems,
    completed,
    gaps,
    officialExams,
    lectureSlides,
    variationsTotal,
    coveragePercent: Math.round((completed / (totalItems - gaps)) * 100),
  };
}

